//! Theme system, btop style: a flat table of named colors plus a few gradients.
//! `t` cycles the built-ins; `--theme <name>` picks one at startup.

use crate::color::{Rgb, rgb};

#[derive(Clone)]
pub struct Theme {
    pub name: &'static str,
    /// Main background (None = leave the terminal's own background).
    pub bg: Option<Rgb>,
    /// What we assume the background looks like when we have to blend against it.
    pub bg_guess: Rgb,
    pub fg: Rgb,
    pub dim: Rgb,
    pub faint: Rgb,
    pub title: Rgb,
    pub hi: Rgb,
    pub accent: Rgb,
    pub good: Rgb,
    pub warn: Rgb,
    /// Panel outlines (binder, card, stats, header rule).
    pub box_binder: Rgb,
    pub box_card: Rgb,
    pub box_stats: Rgb,
    pub box_focus: Rgb,
    /// Meter / graph gradients (low -> high).
    pub meter: [Rgb; 3],
    pub meter_bg: Rgb,
    pub graph: [Rgb; 3],
    /// Inside of a card (behind transparent art pixels).
    pub card_bg: Rgb,
    /// Empty binder slots: the dashed outline (and the faint fill of the old empty-slot silhouette).
    pub slot_line: Rgb,
    pub silhouette: Rgb,
    /// Seen cards: the card stock behind the shadow, and the shadow (the Pokédex "seen" silhouette).
    pub seen_bg: Rgb,
    pub shadow: Rgb,
}

